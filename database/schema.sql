CREATE DATABASE IF NOT EXISTS `02_ccnoms_db` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `02_ccnoms_db`;

CREATE TABLE IF NOT EXISTS `users` (
  UserID INT AUTO_INCREMENT PRIMARY KEY,
  FullName VARCHAR(100) NOT NULL,
  Email VARCHAR(160) NOT NULL UNIQUE,
  PasswordHash VARCHAR(255) NOT NULL,
  Role VARCHAR(30) NOT NULL DEFAULT 'user',
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `technicians` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `Specialization` VARCHAR(255) NOT NULL,
  `Availability` VARCHAR(255) NOT NULL,
  `UserID` INT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_technicians_userid` FOREIGN KEY (`UserID`) REFERENCES `users` (`UserID`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `outage_logs` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `Area` VARCHAR(255) NOT NULL,
  `StartTime` DATETIME NOT NULL,
  `EndTime` DATETIME NULL,
  `Status` VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `tickets` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `IssueType` VARCHAR(255) NOT NULL,
  `Description` TEXT NOT NULL,
  `Status` VARCHAR(255) NOT NULL,
  `ReportedAt` DATETIME NULL,
  `UserID` INT NOT NULL,
  `TechnicianID` INT NULL,
  `OutageID` INT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_tickets_userid` FOREIGN KEY (`UserID`) REFERENCES `users` (`UserID`) ON DELETE RESTRICT,
  CONSTRAINT `fk_tickets_technicianid` FOREIGN KEY (`TechnicianID`) REFERENCES `technicians` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_tickets_outageid` FOREIGN KEY (`OutageID`) REFERENCES `outage_logs` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `ticket_updates` (
  id INT AUTO_INCREMENT PRIMARY KEY,
  `Remarks` TEXT NOT NULL,
  `LoggedAt` DATETIME NULL,
  `TicketID` INT NOT NULL,
  `UserID` INT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `fk_ticket_updates_ticketid` FOREIGN KEY (`TicketID`) REFERENCES `tickets` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_ticket_updates_userid` FOREIGN KEY (`UserID`) REFERENCES `users` (`UserID`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
